package com.linli.news.config

import com.fasterxml.jackson.databind.ObjectMapper
import com.linli.news.model.FeaturedCollectionDefinitionDto
import com.linli.news.service.ArticleTagService
import com.linli.news.service.FeaturedCollectionService
import org.slf4j.LoggerFactory
import org.springframework.boot.ApplicationArguments
import org.springframework.boot.ApplicationRunner
import org.springframework.stereotype.Component

@Component
class DataInitializer(
    private val articleTagService: ArticleTagService,
    private val featuredCollectionService: FeaturedCollectionService,
    private val objectMapper: ObjectMapper
) : ApplicationRunner {

    private val logger = LoggerFactory.getLogger(DataInitializer::class.java)

    override fun run(args: ApplicationArguments?) {
        logger.info("Checking for initial data...")

        // 初始化 Tags
        try {
            val tagsResource = this::class.java.classLoader.getResourceAsStream("tag-definitions.json")
            if (tagsResource != null) {
                val tagsNode = objectMapper.readTree(tagsResource)
                val tagsList = tagsNode.map { node ->
                    node.path("name").asText() to node.path("description").asText()
                }
                articleTagService.initTags(tagsList)
            } else {
                logger.warn("tag-definitions.json not found")
            }
        } catch (e: Exception) {
            logger.error("Failed to init tags: {}", e.message, e)
        }

        // 初始化 Collections
        try {
            val collectionsResource = this::class.java.classLoader.getResourceAsStream("featured-collections.json")
            if (collectionsResource != null) {
                val collectionsNode = objectMapper.readTree(collectionsResource)
                val collectionsList = collectionsNode.map { node ->
                    FeaturedCollectionDefinitionDto(
                        id = 0, // ID will be generated by DB
                        collectionId = node.path("id").asText(),
                        title = node.path("title").asText(),
                        subtitle = node.path("subtitle").asText(null),
                        description = node.path("description").asText(null),
                        colorStart = node.path("colorStart").asText(null),
                        colorEnd = node.path("colorEnd").asText(null)
                    )
                }
                featuredCollectionService.initCollections(collectionsList)
            } else {
                logger.warn("featured-collections.json not found")
            }
        } catch (e: Exception) {
            logger.error("Failed to init collections: {}", e.message, e)
        }
    }
}
